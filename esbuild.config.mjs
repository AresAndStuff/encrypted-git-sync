import esbuild from "esbuild";
import process from "node:process";
import builtins from "builtin-modules";

const banner = `/*
Encrypted Git Sync for Obsidian
This file is generated by esbuild. Edit the sources in src/ instead.
*/`;

const prod = process.argv[2] === "production";

// Node built-ins exist only on desktop. "buffer" must be bundled from npm,
// otherwise require("buffer") fails on mobile and the plugin cannot load.
const nodeBuiltins = builtins.filter((m) => m !== "buffer");

// The plugin itself: bundled to main.js in CommonJS, as Obsidian expects.
const pluginContext = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...nodeBuiltins,
  ],
  format: "cjs",
  platform: "browser",
  target: "es2020",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  minify: prod,
  outfile: "main.js",
});

// Recovery tool: decrypts a cloned repository with Node, without Obsidian.
const recoverBuild = esbuild.build({
  entryPoints: ["src/cli/recover.ts"],
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node20",
  logLevel: "info",
  outfile: "dist/recover.mjs",
  banner: { js: "#!/usr/bin/env node" },
});

if (prod) {
  await pluginContext.rebuild();
  await recoverBuild;
  process.exit(0);
} else {
  await recoverBuild;
  await pluginContext.watch();
}
